'use strict';
const assert=require('node:assert/strict');
const api=require('../auaulandia/presenca-logica.js');
const turma=[{id:'a-1',nome:'Luna <x>',tutor:'Ana & Cia'},{id:'a-2',nome:'Lua',tutor:'Bia'},{id:'a-3',nome:'Sol',tutor:'Cris'}];
function proj(agora,valores,estado,metas,turmaEstado){ return api.montar({dia:'2026-10-14',agora,participantes:turma,turmaEstado:turmaEstado||'pronto',chamada:{estado:estado||'pronto',valores:valores||{}},chamadaMeta:{estado:'pronto',valores:metas||{}}}); }
assert.deepEqual(api.agoraSP('2026-10-14T14:59:00Z'),{dia:'2026-10-14',hora:'11:59',minutos:719});
assert.deepEqual(api.agoraSP('2026-10-14T15:00:00Z'),{dia:'2026-10-14',hora:'12:00',minutos:720});
let p=proj('2026-10-14T14:59:00Z',{ 'a-1':'veio','a-2':'faltou'},'pronto',{'a-2':{estado:'faltou',origem:'manual'}});
assert.deepEqual(p.itens.map(x=>x.estado),['presente','falta-confirmada','aguardando']);
assert.deepEqual(p.totais,{presentes:1,faltasConfirmadas:1,faltasRegistradasConferir:0,aguardando:1,aConferir:0,desconhecidos:0});
p=proj('2026-10-14T15:00:00Z',{});
assert.equal(p.itens[0].rotulo,'A conferir');
assert.equal(p.totais.faltasConfirmadas,0,'o relógio não cria falta');
p=proj('2026-10-14T15:00:00Z',{},'falha');
assert.equal(p.estado,'falha'); assert.equal(p.itens.length,0);
assert.equal(api.impressaoHTML(p,'dia').erro,'dados-incompletos','não imprime vazio como certeza');
assert.match(api.cardHTML(p),/Atualizar presença/,'falha oferece nova tentativa');
p=proj('2026-10-14T15:00:00Z',{'a-2':'faltou'},'pronto',{'a-2':{estado:'faltou',origem:'manual'}});
const dia=api.impressaoHTML(p,'dia'); const faltas=api.impressaoHTML(p,'faltas');
assert.equal(dia.ok,true); assert.match(dia.html,/Luna &lt;x&gt;/); assert.match(dia.html,/Ana &amp; Cia/);
assert.match(faltas.html,/Lua/); assert.doesNotMatch(faltas.html,/Luna &lt;x&gt;/);
assert.match(api.cardHTML(p),/Imprimir \/ salvar PDF/);
assert.match(api.cardHTML(p),/presencaAbrirChamada/);
assert.match(api.cardHTML(p),/Atualizar presença/);
const legado=proj('2026-10-14T15:00:00Z',{'a-2':'faltou'});
assert.equal(legado.itens[1].estado,'falta-registrada-conferir');
assert.equal(legado.totais.faltasConfirmadas,0,'legado sem autoria não vira falta humana');
assert.match(api.cardHTML(legado),/Confirmar falta/);
p=proj('2026-10-14T15:00:00Z',{'a-2':'faltou'},'pronto',{'a-2':{estado:'faltou',origem:'manual',quem:'Monitor <Exemplo>',hora:'12:10'}});
assert.match(p.itens[1].motivo||'',/^$/,'ausência sem motivo não inventa explicação');
const comRegistro=api.impressaoHTML(p,'faltas').html;
assert.match(comRegistro,/Confirmada por Monitor &lt;Exemplo&gt; · 12:10/,'PDF preserva autoria e hora com escape');
assert.match(comRegistro,/@page|table-header-group/,'PDF preserva cabeçalho e margens para lista longa');
assert.equal(proj('2026-10-14T15:00:00Z',{},'pronto',{},'falha').estado,'falha','turma não carregada bloqueia totais');
assert.equal(api.montar({dia:'2026-10-14',agora:'2026-10-14T15:00:00Z',participantes:turma,turmaEstado:'pronto',chamada:{estado:'pronto',valores:{}}}).estado,'carregando','autoria ainda não lida bloqueia totais');
assert.equal(proj('2026-10-15T02:59:00Z',{}).itens[0].estado,'a-conferir','a meia-noite de São Paulo não depende do fuso do aparelho');
console.log('presenca-logica.test.js: ok');
